// Sourcemaps.
//
// The important property here is not the JSON shape — it is that the map
// describes the same build the builder performs. A sourcemap that points
// tooling at the wrong file is worse than no sourcemap, because nothing about
// its output looks wrong.

import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';

import { sourceMapFromProject, sourceMapFromModel, countNodes } from '../src/rbx/sourcemap.js';
import { buildFromProject } from '../src/backends/local/index.js';

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'studio-sourcemap-'));

/** A project on disk, written from a {path: content} map. */
function makeProject(files) {
  const dir = fs.mkdtempSync(path.join(tmp, 'proj-'));
  for (const [rel, content] of Object.entries(files)) {
    const file = path.join(dir, rel);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  }
  return dir;
}

const CYCLE_PROJECT = path.join(process.cwd(), 'examples', 'cycle', 'default.project.json');

/**
 * Every node, flattened, with its path from the DataModel down.
 *
 * The DataModel itself contributes no path segment: `game.ReplicatedStorage.A`
 * is the path of `A`, not `Game.ReplicatedStorage.A`.
 */
function flatten(node, prefix = '', isRoot = true) {
  const here = isRoot ? '' : prefix ? `${prefix}.${node.name}` : node.name;
  const out = [{ ...node, path: here }];
  for (const child of node.children || []) out.push(...flatten(child, here, false));
  return out;
}

test('the map has the shape Luau tooling expects', () => {
  const { sourcemap } = sourceMapFromProject(CYCLE_PROJECT);
  assert.equal(sourcemap.className, 'DataModel');
  assert.equal(sourcemap.name, 'Cycle');
  assert.deepEqual(sourcemap.filePaths, ['default.project.json']);
  assert.ok(Array.isArray(sourcemap.children));

  for (const node of flatten(sourcemap)) {
    assert.equal(typeof node.name, 'string', `${node.path} needs a name`);
    assert.equal(typeof node.className, 'string', `${node.path} needs a className`);
    assert.ok(Array.isArray(node.filePaths), `${node.path} needs filePaths`);
    assert.ok(Array.isArray(node.children), `${node.path} needs children`);
  }
});

test('a script maps to the file that produced it', () => {
  const { sourcemap } = sourceMapFromProject(CYCLE_PROJECT);
  const a = flatten(sourcemap).find((n) => n.name === 'A');
  assert.equal(a.className, 'ModuleScript');
  assert.deepEqual(a.filePaths, [path.join('src', 'A.luau')]);
  assert.equal(a.instancePath, 'game.ReplicatedStorage.Shared.A');
});

test('a directory with an init script reports both the directory and the script', () => {
  const dir = makeProject({
    'default.project.json': JSON.stringify({
      name: 'Init',
      tree: { $className: 'DataModel', ReplicatedStorage: { $className: 'ReplicatedStorage', Lib: { $path: 'lib' } } },
    }),
    'lib/init.luau': 'return 1\n',
    'lib/Extra.luau': 'return 2\n',
  });
  const { sourcemap } = sourceMapFromProject(path.join(dir, 'default.project.json'));
  const lib = flatten(sourcemap).find((n) => n.name === 'Lib');
  assert.equal(lib.className, 'ModuleScript', 'an init script decides the class');
  assert.deepEqual(lib.filePaths, ['lib'], 'the instance is the directory');
  assert.equal(lib.scriptFile, 'lib/init.luau', 'and the source lives in the init script');
});

test('the map is generated by the build walk, so it cannot disagree with a build', () => {
  // The strong version of this: every filePath in the map must exist, and the
  // instance it belongs to must be an instance the build actually produced.
  const dir = makeProject({
    'default.project.json': JSON.stringify({
      name: 'Agree',
      tree: {
        $className: 'DataModel',
        ReplicatedStorage: { $className: 'ReplicatedStorage', Shared: { $path: 'src' } },
        ServerScriptService: { $className: 'ServerScriptService', Main: { $path: 'src/Main.server.luau' } },
      },
    }),
    'src/Util.luau': 'return {}\n',
    'src/Nested/init.luau': 'return {}\n',
    'src/Main.server.luau': 'print("hi")\n',
  });
  const project = path.join(dir, 'default.project.json');
  const { sourcemap } = sourceMapFromProject(project);
  const { roots } = buildFromProject(project);

  // Build every instance path the builder produced.
  const built = new Set();
  const visit = (inst, prefix) => {
    const here = prefix ? `${prefix}.${inst.name}` : inst.name;
    built.add(here);
    for (const child of inst.children) visit(child, here);
  };
  for (const root of roots) visit(root, '');

  for (const node of flatten(sourcemap)) {
    // The map's root is the DataModel itself; the build's roots are that
    // DataModel's children, so the root is checked separately below.
    if (node.path === '') {
      assert.equal(node.instancePath, 'game');
      continue;
    }
    const relative = node.instancePath.replace(/^game\./, '');
    assert.ok(built.has(relative), `${node.instancePath} is in the map but not in the build`);
    for (const file of node.filePaths) {
      assert.ok(fs.existsSync(path.join(dir, file)), `${node.path}: ${file} does not exist`);
    }
    if (node.scriptFile) {
      assert.ok(fs.existsSync(path.join(dir, node.scriptFile)), `${node.path}: ${node.scriptFile} missing`);
    }
  }
});

test('paths are relative to the project file and use forward slashes', () => {
  const { sourcemap } = sourceMapFromProject(CYCLE_PROJECT);
  for (const node of flatten(sourcemap)) {
    for (const file of [...node.filePaths, ...(node.scriptFile ? [node.scriptFile] : [])]) {
      assert.ok(!file.startsWith('/'), `${file} should not be absolute`);
      assert.ok(!file.includes(path.sep === '/' ? '\u0000' : path.sep), `${file} should use forward slashes`);
      assert.ok(!file.startsWith('..'), `${file} should be inside the project`);
    }
  }
});

test('only scripts and their ancestors are kept by default', () => {
  const dir = makeProject({
    'default.project.json': JSON.stringify({
      name: 'Prune',
      tree: {
        $className: 'DataModel',
        Workspace: {
          $className: 'Workspace',
          Decoration: { $className: 'Folder', Part: { $className: 'Part' } },
          Scripts: { $className: 'Folder', Run: { $path: 'run.server.luau' } },
        },
      },
    }),
    'run.server.luau': 'print(1)\n',
  });
  const { sourcemap } = sourceMapFromProject(path.join(dir, 'default.project.json'));
  const paths = flatten(sourcemap).map((n) => n.path);
  assert.ok(paths.includes('Workspace.Scripts.Run'), 'the script is kept');
  assert.ok(paths.includes('Workspace.Scripts'), 'and its parent, so a require can be resolved');
  assert.ok(!paths.includes('Workspace.Decoration'), 'a tree with no scripts in it is dropped');

  // ...and the opt-in brings it all back.
  const { sourcemap: full } = sourceMapFromProject(path.join(dir, 'default.project.json'), {
    includeNonScripts: true,
  });
  const allPaths = flatten(full).map((n) => n.path);
  assert.ok(allPaths.includes('Workspace.Decoration.Part'));
});

test('a built place can be mapped even though nothing on disk produced it', () => {
  // This is the case Rojo has no answer for: a .rbxl and no project.
  const dir = makeProject({
    'default.project.json': JSON.stringify({
      name: 'Place',
      tree: { $className: 'DataModel', ReplicatedStorage: { $className: 'ReplicatedStorage', Mod: { $path: 'Mod.luau' } } },
    }),
    'Mod.luau': 'return { value = 7 }\n',
  });
  const { roots } = buildFromProject(path.join(dir, 'default.project.json'));
  const { sourcemap } = sourceMapFromModel(roots);

  const mod = flatten(sourcemap).find((n) => n.name === 'Mod');
  assert.equal(mod.className, 'ModuleScript');
  assert.deepEqual(mod.filePaths, [], 'no file on disk produced this instance');
  assert.equal(mod.instancePath, 'game.ReplicatedStorage.Mod');

  // The hash is what makes it useful: it identifies the source without a file.
  const expected = crypto
    .createHash('sha256')
    .update('return { value = 7 }\n', 'utf8')
    .digest('hex')
    .slice(0, 32);
  assert.equal(mod.sourceHash, expected);
  assert.equal(mod.sourceLines, 2);
});

test('two instances built from one file have the same hash', () => {
  const dir = makeProject({
    'default.project.json': JSON.stringify({
      name: 'Dup',
      tree: {
        $className: 'DataModel',
        ReplicatedStorage: { $className: 'ReplicatedStorage', One: { $path: 'Same.luau' } },
        ServerStorage: { $className: 'ServerStorage', Two: { $path: 'Same.luau' } },
      },
    }),
    'Same.luau': 'return "same"\n',
  });
  const { sourcemap } = sourceMapFromProject(path.join(dir, 'default.project.json'));
  const one = flatten(sourcemap).find((n) => n.name === 'One');
  const two = flatten(sourcemap).find((n) => n.name === 'Two');
  // The project map says it by pointing at the same path...
  assert.deepEqual(one.filePaths, two.filePaths);
  assert.equal(one.instancePath, 'game.ReplicatedStorage.One');
  assert.equal(two.instancePath, 'game.ServerStorage.Two');

  // ...and the model map says it by hash, which is all a place has.
  const { roots } = buildFromProject(path.join(dir, 'default.project.json'));
  const fromPlace = flatten(sourceMapFromModel(roots).sourcemap);
  assert.equal(
    fromPlace.find((n) => n.name === 'One').sourceHash,
    fromPlace.find((n) => n.name === 'Two').sourceHash,
  );
});

test('a project warning surfaces instead of producing a quietly wrong map', () => {
  const dir = makeProject({
    'default.project.json': JSON.stringify({
      name: 'Warn',
      tree: { $className: 'DataModel', ReplicatedStorage: { $className: 'ReplicatedStorage', Shared: { $path: 'src' } } },
    }),
    'src/notes.md': 'not an instance\n',
  });
  const { warnings } = sourceMapFromProject(path.join(dir, 'default.project.json'));
  assert.ok(
    warnings.some((w) => w.code === 'skipped-file'),
    `expected a skipped-file warning, got ${JSON.stringify(warnings)}`,
  );
});

test('node counts cover the whole tree', () => {
  const dir = makeProject({
    'default.project.json': JSON.stringify({
      name: 'Count',
      tree: {
        $className: 'DataModel',
        ReplicatedStorage: {
          $className: 'ReplicatedStorage',
          A: { $path: 'A.luau' },
          B: { $path: 'B.luau' },
        },
      },
    }),
    'A.luau': 'return 1\n',
    'B.luau': 'return 2\n',
  });
  const { sourcemap } = sourceMapFromProject(path.join(dir, 'default.project.json'), {
    includeNonScripts: true,
  });
  // DataModel, ReplicatedStorage, A, B
  assert.equal(countNodes(sourcemap), 4);
});
